function buildLocalizedMeaning(name: string, reversed: boolean) {
  if (reversed) {
    return `${name} ကို ပြောင်းလဲနေသောအနေအထားတွင် ကြည့်မည်ဆိုပါက သင်၏ အကန့်အသတ်များ၊ အားနည်းချက်များနှင့် အရာများကို ပြန်လည်သိရှိစေမည်ဖြစ်သည်။`;
  }
  return `${name} သည် သင်၏ အတွေးအခေါ်၊ စွမ်းအားနှင့် ရည်ရွယ်ချက်ကို အလင်းပေးပြီး နောက်တစ်ဆင့််အတွက် အချက်အလက်များစွာကို တိုးပွားစေပါသည်။`;
}

export function getLocalizedCard(card: Card, language: string | undefined) {
  if (language !== 'my') {
    return card;
  }

  return {
    ...card,
    name: cardNameTranslations[card.id] ?? card.name,
    meaning: {
      upright: buildLocalizedMeaning(cardNameTranslations[card.id] ?? card.name, false),
      reversed: buildLocalizedMeaning(cardNameTranslations[card.id] ?? card.name, true),
    },
  };
}

